import ToothMap from '@/components/ToothMap';
import { Plus, StickyNote, Download, ChevronDown, Activity, Search } from 'lucide-react';
import PatientProgressLine from '@/components/dentist/PatientProgressLine';

// EHR export (pillar 3): opens a printable enamel-health timeline for a patient
// in a new window and triggers the print dialog — so the dentist can hand it to
// the patient or file it ahead of an appointment. Pure client-side, no backend.
function exportTimeline(client, scans) {
  const sorted = [...scans].sort((a, b) => new Date(a.created_date) - new Date(b.created_date));
  const rows = sorted.map((s) => `<tr>
    <td>${new Date(s.created_date).toLocaleDateString()}</td>
    <td>${s.shade || '—'}</td>
    <td>${s.score ?? '—'}</td>
    <td>${s.dental_health_score ?? '—'}</td>
    <td>${s.gum_health || '—'}</td>
    <td>${s.plaque_level || '—'}</td>
    <td>${(s.dental_health_issues || []).join(', ') || '—'}</td>
  </tr>`).join('');
  const w = window.open('', '_blank');
  if (!w) return;
  w.document.write(`<!doctype html><html><head><title>${client.client_name} — teewai timeline</title>
    <style>body{font-family:Inter,system-ui,sans-serif;color:#0f2e2e;margin:32px}h1{font-size:20px;margin:0 0 4px}p.sub{color:#666;margin:0 0 20px;font-size:13px}table{width:100%;border-collapse:collapse;font-size:12px}th,td{border:1px solid #e0e0e0;padding:8px;text-align:left}th{background:#f0fdfa;color:#0f766e}tr:nth-child(even){background:#fafafa}.note{margin-top:20px;padding:12px;background:#f0fdfa;border-radius:8px;font-size:13px}.foot{margin-top:24px;color:#999;font-size:11px}</style></head>
    <body><h1>${client.client_name}</h1><p class="sub">${client.client_email} · Exported ${new Date().toLocaleDateString()} · teewai dentist portal</p>
    <table><thead><tr><th>Date</th><th>Shade</th><th>Whiteness</th><th>Health</th><th>Gum</th><th>Plaque</th><th>Issues</th></tr></thead><tbody>${rows || '<tr><td colspan=7>No scans recorded</td></tr>'}</tbody></table>
    <div class="note"><strong>Clinical notes:</strong><br>${(client.notes || 'No notes recorded.').replace(/\n/g, '<br>')}</div>
    <div class="foot">Generated by teewai · Wellness estimates, not a clinical diagnosis.</div></body></html>`);
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 300);
}

// Inline SVG whiteness-progression sparkline — no chart lib needed.
function Sparkline({ values }) {
  if (values.length < 2) return null;
  const w = 120, h = 36, pad = 3;
  const min = Math.min(...values), max = Math.max(...values);
  const span = Math.max(1, max - min);
  const pts = values.map((v, i) => {
    const x = pad + (i / (values.length - 1)) * (w - pad * 2);
    const y = h - pad - ((v - min) / span) * (h - pad * 2);
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  }).join(' ');
  return (
    <svg width={w} height={h} className="overflow-visible">
      <polyline points={pts} fill="none" stroke="hsl(var(--olo))" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
      {values.map((v, i) => {
        const x = pad + (i / (values.length - 1)) * (w - pad * 2);
        const y = h - pad - ((v - min) / span) * (h - pad * 2);
        return <circle key={i} cx={x} cy={y} r="2" fill="hsl(var(--olo))" />;
      })}
    </svg>
  );
}

// Patient roster — the clinic's patient chart. Search by name/email, add by
// email, expand each patient to see their latest scan, an odontogram (tooth
// chart) from that scan, whiteness trend, full scan history, clinical notes,
// and a printable EHR export. Scan photos load through the ownership-verified
// ScanImage proxy (the bucket is private).
export default function DentistPatients({ clients, scans, user, reload }) {
  const [showAdd, setShowAdd] = useState(false);
  const [newClient, setNewClient] = useState({ client_name: '', client_email: '' });
  const [saving, setSaving] = useState(false);
  const [expanded, setExpanded] = useState(null);
  const [notesDraft, setNotesDraft] = useState({});
  const [savingNotes, setSavingNotes] = useState(null);
  const [query, setQuery] = useState('');

  const addClient = async (e) => {
    e.preventDefault();
    setSaving(true);
    try {
      await dentistClients.create({ ...newClient, dentist_id: user.id });
      setNewClient({ client_name: '', client_email: '' });
      setShowAdd(false);
      await reload();
    } catch {} finally { setSaving(false); }
  };

  const saveNotes = async (client) => {
    const text = notesDraft[client.id];
    if (text === undefined) return;
    setSavingNotes(client.id);
    try { await dentistClients.update(client.id, { notes: text }); await reload(); }
    catch {} finally { setSavingNotes(null); }
  };

  const clientScans = (email) => scans.filter((s) => s.patient_email === email)
    .sort((a, b) => new Date(b.created_date) - new Date(a.created_date));

  const q = query.trim().toLowerCase();
  const filtered = q
    ? clients.filter((c) => (c.client_name || '').toLowerCase().includes(q) || (c.client_email || '').toLowerCase().includes(q))
    : clients;

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between gap-2">
        <h2 className="font-heading font-600 text-lg">Your patients</h2>
        <button onClick={() => setShowAdd(!showAdd)}
          className="inline-flex items-center gap-2 bg-olo text-white text-sm font-semibold px-4 py-2.5 rounded-xl hover:scale-105 transition-transform olo-glow">
          <Plus className="w-4 h-4" /> Add patient
        </button>
      </div>

      {/* Patient search — every patient roster needs it */}
      {clients.length > 0 && (
        <div className="relative">
          <Search className="w-4 h-4 text-muted-foreground absolute left-3 top-1/2 -translate-y-1/2" />
          <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Search by name or email…"
            className="w-full h-11 pl-9 pr-3 rounded-xl border border-border bg-card focus:border-olo focus:outline-none text-sm" />
        </div>
      )}

      {showAdd && (
        <form onSubmit={addClient} className="p-4 rounded-2xl border border-border bg-card grid sm:grid-cols-3 gap-3 items-end">
          <div className="space-y-1">
            <label className="text-[10px] text-muted-foreground uppercase tracking-wider">Name</label>
            <input value={newClient.client_name} onChange={(e) => setNewClient({ ...newClient, client_name: e.target.value })} required placeholder="Jane Doe"
              className="w-full h-11 px-3 rounded-xl border border-border bg-background focus:border-olo focus:outline-none" />
          </div>
          <div className="space-y-1">
            <label className="text-[10px] text-muted-foreground uppercase tracking-wider">Email</label>
            <input type="email" value={newClient.client_email} onChange={(e) => setNewClient({ ...newClient, client_email: e.target.value })} required placeholder="jane@email.com"
              className="w-full h-11 px-3 rounded-xl border border-border bg-background focus:border-olo focus:outline-none" />
          </div>
          <button type="submit" disabled={saving} className="h-11 bg-olo text-white font-semibold rounded-xl hover:opacity-90 disabled:opacity-50 inline-flex items-center justify-center gap-2">
            {saving ? <Spinner size={16} /> : 'Add to roster'}
          </button>
          <p className="text-xs text-muted-foreground sm:col-span-3">When this patient scans their teeth, results appear here automatically.</p>
        </form>
      )}

      {clients.length === 0 ? (
        <div className="text-center py-14 p-8 rounded-3xl border border-border bg-card">
          <div className="w-14 h-14 rounded-2xl bg-olo/10 flex items-center justify-center mx-auto mb-4"><Activity className="w-7 h-7 text-olo" /></div>
          <h3 className="font-heading font-600 text-lg mb-1">No patients yet</h3>
          <p className="text-muted-foreground text-sm mb-5 max-w-sm mx-auto">Add your first patient by email — their scans show up here automatically.</p>
          <button onClick={() => setShowAdd(true)} className="inline-flex items-center gap-2 bg-olo text-white font-semibold px-5 py-2.5 rounded-xl hover:scale-105 transition-transform olo-glow">
            <Plus className="w-4 h-4" /> Add your first patient
          </button>
        </div>
      ) : filtered.length === 0 ? (
        <div className="text-center py-12 p-8 rounded-2xl border border-border bg-card">
          <p className="text-muted-foreground text-sm">No patients match “{query}”.</p>
        </div>
      ) : (
        <div className="space-y-2.5">
          {filtered.map((c) => {
            const cScans = clientScans(c.client_email);
            const latest = cScans[0];
            const isOpen = expanded === c.id;
            const trend = [...cScans].reverse().map((s) => s.score).filter((v) => v != null);
            return (
              <div key={c.id} className="rounded-2xl border border-border bg-card overflow-hidden">
                <button onClick={() => setExpanded(isOpen ? null : c.id)} className="w-full flex items-center gap-3 p-4 text-left hover:bg-olo/5 transition-colors">
                  <div className="w-11 h-11 rounded-xl bg-olo/10 flex items-center justify-center font-heading font-700 text-olo flex-shrink-0">
                    {c.client_name.charAt(0).toUpperCase()}
                  </div>
                  <div className="flex-1 min-w-0">
                    <p className="font-medium truncate">{c.client_name}</p>
                    <p className="text-xs text-muted-foreground truncate">{c.client_email}</p>
                  </div>
                  {latest ? (
                    <div className="hidden sm:flex items-center gap-4 text-sm">
                      <div className="text-center"><p className="font-heading font-700 text-olo text-base leading-none">{latest.score ?? '—'}</p><p className="text-[10px] text-muted-foreground mt-0.5">whiteness</p></div>
                      <div className="text-center"><p className="font-heading font-700 text-emerald-500 text-base leading-none">{latest.dental_health_score ?? '—'}</p><p className="text-[10px] text-muted-foreground mt-0.5">health</p></div>
                      <div className="text-center"><p className="font-heading font-700 text-base leading-none">{cScans.length}</p><p className="text-[10px] text-muted-foreground mt-0.5">scans</p></div>
                    </div>
                  ) : <span className="text-xs text-muted-foreground hidden sm:block">No scans</span>}
                  <ChevronDown className={`w-4 h-4 text-muted-foreground transition-transform flex-shrink-0 ${isOpen ? 'rotate-180' : ''}`} />
                </button>

                {isOpen && (
                  <div className="p-4 border-t border-border bg-muted/30 space-y-4">
                    {latest ? (
                      <div className="flex items-center gap-3 p-3 rounded-xl bg-card border border-border">
                        <ScanImage url={latest.image_url} alt="Scan" className="w-14 h-14 rounded-lg object-cover flex-shrink-0" fallback={<div className="w-14 h-14 rounded-lg bg-muted flex-shrink-0" />} />
                        <div className="flex-1 min-w-0">
                          <p className="text-sm font-medium">Latest scan · {new Date(latest.created_date).toLocaleDateString()}</p>
                          <p className="text-xs text-muted-foreground">Shade {latest.shade || '—'} · Gum {latest.gum_health || '—'} · Plaque {latest.plaque_level || '—'}</p>
                          {latest.dental_health_issues?.length > 0 && <p className="text-xs text-amber-500 mt-0.5">Issues: {latest.dental_health_issues.join(', ')}</p>}
                        </div>
                        <Link to={`/results/${latest.id}`} className="text-xs font-medium text-olo hover:underline flex-shrink-0">View</Link>
                      </div>
                    ) : (
                      <p className="text-xs text-muted-foreground">No scans yet — they'll appear here when the patient scans.</p>
                    )}

                    {/* Progress line — read-only summary from report data
                        (scores, shades, dates). Shows whenever the dentist can
                        see the patient's scans, even if photos are gated. */}
                    {cScans.length > 0 && <PatientProgressLine scans={cScans} />}

                    {/* Odontogram (tooth chart) from the latest scan — a core
                        dental-EHR feature. Reuses the patient-facing ToothMap. */}
                    {latest && Array.isArray(latest.tooth_analysis) && latest.tooth_analysis.length > 0 && (
                      <ToothMap scan={latest} />
                    )}

                    {trend.length >= 2 && (
                      <div className="p-3 rounded-xl bg-card border border-border">
                        <p className="text-[10px] text-muted-foreground uppercase tracking-wider mb-1">Whiteness trend</p>
                        <div className="flex items-center gap-3">
                          <Sparkline values={trend} />
                          <span className="text-xs text-muted-foreground">{trend[0]} → {trend[trend.length - 1]}</span>
                        </div>
                      </div>
                    )}

                    {cScans.length > 1 && (
                      <div className="space-y-2">
                        <p className="text-[10px] text-muted-foreground uppercase tracking-wider">Scan history</p>
                        {cScans.map((s) => (
                          <Link key={s.id} to={`/results/${s.id}`} className="flex items-center gap-3 p-2.5 rounded-lg bg-card border border-border hover:border-olo/40 transition-colors">
                            <ScanImage url={s.image_url} alt="Scan" className="w-9 h-9 rounded-lg object-cover flex-shrink-0" fallback={<div className="w-9 h-9 rounded-lg bg-muted flex-shrink-0" />} />
                            <span className="text-xs text-muted-foreground flex-1">{new Date(s.created_date).toLocaleDateString(undefined, { month: 'short', day: 'numeric' })}</span>
                            <span className="text-xs font-medium text-olo">{s.score ?? '—'} W</span>
                            <span className="text-xs font-medium text-emerald-500">{s.dental_health_score ?? '—'} H</span>
                          </Link>
                        ))}
                      </div>
                    )}

                    <div className="flex flex-col sm:flex-row gap-2 sm:items-end">
                      <div className="flex-1 space-y-1">
                        <label className="text-[10px] text-muted-foreground uppercase tracking-wider flex items-center gap-1"><StickyNote className="w-3 h-3" /> Clinical notes</label>
                        <textarea defaultValue={c.notes || ''} onChange={(e) => setNotesDraft({ ...notesDraft, [c.id]: e.target.value })} rows={2} placeholder="Add your observations…"
                          className="w-full p-3 rounded-xl border border-border bg-card focus:border-olo focus:outline-none resize-none text-sm" />
                        <button onClick={() => saveNotes(c)} disabled={savingNotes === c.id} className="text-xs font-medium text-olo hover:underline disabled:opacity-50">
                          {savingNotes === c.id ? 'Saving…' : 'Save notes'}
                        </button>
                      </div>
                      {cScans.length > 0 && (
                        <button onClick={() => exportTimeline(c, cScans)} className="inline-flex items-center gap-1.5 border border-border text-muted-foreground text-xs font-medium py-2 px-3 rounded-xl hover:text-olo hover:border-olo/30 transition-colors whitespace-nowrap">
                          <Download className="w-3.5 h-3.5" /> Export timeline
                        </button>
                      )}
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}