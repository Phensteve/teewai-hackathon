import { Link } from 'react-router-dom';
import { Stethoscope, Share2, Download, MapPinned } from 'lucide-react';

// Professional handoff (pillar: professional integration). Lets a user share
// their AI shade report with a real dentist — print/PDF a clean report, share a
// summary via the Web Share API on mobile, or find a teewai clinic near them.
// Pure client-side; pairs with the dentist portal's EHR export.

const fmtDate = (d) => (d ? new Date(d).toLocaleDateString() : '—');

function buildReportHTML(scan, userName) {
  const issues = (scan.dental_health_issues || []).join(', ') || 'None detected';
  const stains = (scan.stain_types || scan.stains_detected || []).join(', ') || 'None detected';
  const recs = (scan.recommendations || []).map((r) =>
    `<li><strong>${r.title || ''}</strong>${r.description ? ` — ${r.description}` : ''}${r.frequency ? ` (${r.frequency})` : ''}</li>`
  ).join('');
  return `<!doctype html><html><head><title>teewai shade report</title>
    <style>body{font-family:Inter,system-ui,sans-serif;color:#0f2e2e;margin:32px;max-width:680px}h1{font-size:22px;margin:0 0 2px}p.sub{color:#666;margin:0 0 24px;font-size:13px}.grid{display:grid;grid-template-columns:1fr 1fr;gap:12px;margin-bottom:20px}.card{border:1px solid #e0e0e0;border-radius:10px;padding:14px}.card h3{margin:0 0 4px;font-size:12px;text-transform:uppercase;color:#0f766e;letter-spacing:.05em}.card .v{font-size:22px;font-weight:700;margin:0}.sec{margin-bottom:18px}.sec h2{font-size:14px;margin:0 0 6px;color:#0f766e}ul{margin:0;padding-left:18px;font-size:13px;line-height:1.6}.note{background:#f0fdfa;border-radius:8px;padding:12px;font-size:13px;line-height:1.6}.foot{margin-top:24px;color:#999;font-size:11px}</style></head>
    <body><h1>teewai AI shade report</h1><p class="sub">${userName || 'Patient'} · ${fmtDate(scan.created_date)} · teewai</p>
    <div class="grid">
      <div class="card"><h3>Whiteness</h3><p class="v">${scan.score ?? '—'}/100</p><p>Shade: ${scan.shade || '—'}${scan.shade_code ? ` (${scan.shade_code})` : ''}</p></div>
      <div class="card"><h3>Dental health</h3><p class="v">${scan.dental_health_score ?? '—'}/100</p><p>Gum: ${scan.gum_health || '—'} · Plaque: ${scan.plaque_level || '—'}</p></div>
    </div>
    <div class="sec"><h2>Stain sources</h2><p>${stains}</p></div>
    <div class="sec"><h2>Issues flagged</h2><p>${issues}</p></div>
    ${recs ? `<div class="sec"><h2>Recommendations</h2><ul>${recs}</ul></div>` : ''}
    ${scan.ai_feedback ? `<div class="sec"><h2>AI summary</h2><div class="note">${scan.ai_feedback.replace(/\n/g, '<br>')}</div></div>` : ''}
    <div class="foot">Generated by teewai · A wellness companion, not a clinical diagnosis. Share with your dentist for professional care.</div></body></html>`;
}

function shareText(scan) {
  return `My teewai smile report — Whiteness ${scan.score ?? '—'}/100 (shade ${scan.shade || '—'}), Dental health ${scan.dental_health_score ?? '—'}/100. Generated by teewai.`;
}

export default function ShareReportCard({ scan, userName }) {
  const printReport = () => {
    const w = window.open('', '_blank');
    if (!w) return;
    w.document.write(buildReportHTML(scan, userName));
    w.document.close();
    w.focus();
    setTimeout(() => w.print(), 300);
  };

  const shareReport = async () => {
    if (navigator.share) {
      try { await navigator.share({ title: 'My teewai smile report', text: shareText(scan) }); return; } catch {}
    }
    printReport();
  };

  return (
    <div className="mt-4 p-5 rounded-2xl border border-olo/20 bg-gradient-to-br from-olo/5 to-card">
      <div className="flex items-start gap-3">
        <div className="w-10 h-10 rounded-xl bg-olo/10 flex items-center justify-center flex-shrink-0">
          <Stethoscope className="w-5 h-5 text-olo" />
        </div>
        <div className="flex-1 min-w-0">
          <h3 className="font-heading font-600 text-sm">Share with your dentist</h3>
          <p className="text-xs text-muted-foreground mt-0.5">Hand your AI shade report to a real dentist — print it, share it, or find a teewai clinic near you.</p>
          <div className="mt-3 flex flex-wrap gap-2">
            <button onClick={shareReport} className="inline-flex items-center gap-1.5 bg-olo text-white text-xs font-semibold px-3 py-2 rounded-lg hover:opacity-90 transition-opacity">
              <Share2 className="w-3.5 h-3.5" /> Share report
            </button>
            <button onClick={printReport} className="inline-flex items-center gap-1.5 border border-border text-foreground text-xs font-medium px-3 py-2 rounded-lg hover:bg-muted/50 transition-colors">
              <Download className="w-3.5 h-3.5" /> Print / PDF
            </button>
            <Link to="/find-dentist" className="inline-flex items-center gap-1.5 border border-olo/30 text-olo text-xs font-medium px-3 py-2 rounded-lg hover:bg-olo/5 transition-colors">
              <MapPinned className="w-3.5 h-3.5" /> Find a dentist
            </Link>
          </div>
        </div>
      </div>
    </div>
  );
}